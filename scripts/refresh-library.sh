#!/bin/sh
set -eu
remote=${MANGA_REMOTE:-/remote}
library=${MANGA_LIBRARY:-/home/suwayomi/.local/share/Tachidesk/local}
mkdir -p "$library"
count=0
pending=0

check_readable_directory() {
    if ! timeout 45 ls -a "$1" >/dev/null; then
        printf 'Cannot list manga directory: %s\n' "$1" >&2
        return 1
    fi
}

# Unwrap a chain of single directories only when its contents identify a
# chapter layout. Keep the final directory containing images as one chapter.
# Ambiguous structures stay as they were; existing local links are untouched.
resolve_wrapped_source() {
    resolved_source=$1
    scan_dir=$1
    depth=0
    while [ "$depth" -lt 16 ]; do
        check_readable_directory "$scan_dir"
        dir_count=0
        other_count=0
        only_dir=
        for entry in "$scan_dir"/*; do
            [ -e "$entry" ] || continue
            if [ -d "$entry" ] && [ ! -L "$entry" ]; then
                dir_count=$((dir_count+1))
                only_dir=$entry
                [ "$dir_count" -le 1 ] || break
            else
                other_count=$((other_count+1))
                break
            fi
        done
        [ "$dir_count" -eq 1 ] && [ "$other_count" -eq 0 ] || break

        check_readable_directory "$only_dir"

        child_dirs=0
        image_dirs=0
        images=0
        archives=0
        other_children=0
        for child in "$only_dir"/*; do
            [ -e "$child" ] || continue
            if [ -d "$child" ] && [ ! -L "$child" ]; then
                check_readable_directory "$child"
                child_dirs=$((child_dirs+1))
                for image in "$child"/*; do
                    [ -f "$image" ] || continue
                    case "$image" in
                        *.jpg|*.JPG|*.jpeg|*.JPEG|*.png|*.PNG|*.webp|*.WEBP|*.gif|*.GIF|*.avif|*.AVIF)
                            image_dirs=$((image_dirs+1))
                            break
                            ;;
                    esac
                done
            elif [ -f "$child" ]; then
                case "$child" in
                    *.jpg|*.JPG|*.jpeg|*.JPEG|*.png|*.PNG|*.webp|*.WEBP|*.gif|*.GIF|*.avif|*.AVIF)
                        images=$((images+1)) ;;
                    *.zip|*.ZIP|*.cbz|*.CBZ|*.rar|*.RAR|*.cbr|*.CBR|*.epub|*.EPUB)
                        archives=$((archives+1)) ;;
                    *) other_children=$((other_children+1)) ;;
                esac
            else
                other_children=$((other_children+1))
            fi
        done

        # A directory with images is itself a chapter, not a wrapper.
        if [ "$images" -gt 0 ]; then
            resolved_source=$scan_dir
            break
        fi
        if [ "$archives" -gt 0 ] ||
           { [ "$child_dirs" -ge 2 ] && [ "$image_dirs" -eq "$child_dirs" ] && [ "$other_children" -eq 0 ]; }; then
            resolved_source=$only_dir
            break
        fi
        # Follow a possible wrapper chain tentatively. Do not commit any
        # unwrapping unless a recognizable chapter layout is reached.
        [ "$child_dirs" -eq 1 ] && [ "$other_children" -eq 0 ] || break
        scan_dir=$only_dir
        depth=$((depth+1))
    done
}

index_directory() {
    source_dir=$1
    book_dir=$2
    check_readable_directory "$source_dir"
    # Migrate only the whole-directory links generated by the old indexer.
    # The originals are retained in a hidden directory for rollback.
    if [ -L "$book_dir" ]; then
        if [ "$(readlink "$book_dir")" != "$source_dir" ]; then
            printf 'Preserved custom link: %s\n' "$book_dir" >&2
            return
        fi
        mkdir -p "$library/.mapping-backup"
        backup="$library/.mapping-backup/${book_dir##*/}"
        if [ -e "$backup" ] || [ -L "$backup" ]; then
            printf 'Backup already exists; preserved link: %s\n' "$book_dir" >&2
            return
        fi
        mv "$book_dir" "$backup"
    fi
    mkdir -p "$book_dir"
    resolve_wrapped_source "$source_dir"
    for chapter in "$resolved_source"/*; do
        [ -e "$chapter" ] || continue
        chapter_name=${chapter##*/}
        destination="$book_dir/$chapter_name"
        if [ ! -e "$destination" ] && [ ! -L "$destination" ]; then
            case "$chapter_name" in
                cover.*|Cover.*|COVER.*|ComicInfo.xml)
                    # Covers and metadata belong on the writable local disk.
                    [ -f "$chapter" ] && cp "$chapter" "$destination"
                    ;;
                *) ln -s "$chapter" "$destination" ;;
            esac
        fi
    done
    # Do not probe every remote archive looking for embedded ComicInfo.xml.
    # An explicit ComicInfo.xml still takes precedence in Suwayomi.
    if [ ! -e "$book_dir/ComicInfo.xml" ]; then
        touch "$book_dir/.noxml"
    fi
}

check_readable_directory "$remote"
for path in "$remote"/*; do
    [ -e "$path" ] || continue
    name=${path##*/}
    case "$name" in .*) continue ;; esac
    # Cloud imports with nested layouts use explicit chapter links. Avoid
    # indexing the extraction wrapper a second time as an empty extra book.
    if [ -f "$library/.cloud-import-excludes" ] &&
        grep -Fqx -- "$name" "$library/.cloud-import-excludes"; then
        continue
    fi
    if [ -d "$path" ]; then
        index_directory "$path" "$library/$name"
        count=$((count+1))
    else
        case "$name" in
            *.rar|*.RAR|*.cbr|*.CBR)
                # These cloud imports include password-protected RAR headers.
                # Keep prior generated mappings recoverable but out of scans.
                title=${name%.*}
                destination="$library/$title/$name"
                if [ -L "$destination" ] && [ "$(readlink "$destination")" = "$path" ]; then
                    mkdir -p "$library/.pending-rar"
                    if [ ! -e "$library/.pending-rar/$title" ]; then
                        mv "$library/$title" "$library/.pending-rar/$title"
                    fi
                fi
                pending=$((pending+1))
                ;;
            *.zip|*.ZIP|*.cbz|*.CBZ|*.epub|*.EPUB)
                title=${name%.*}
                mkdir -p "$library/$title"
                destination="$library/$title/$name"
                if [ ! -e "$destination" ] && [ ! -L "$destination" ]; then
                    ln -s "$path" "$destination"
                fi
                [ -e "$library/$title/ComicInfo.xml" ] || touch "$library/$title/.noxml"
                count=$((count+1))
                ;;
        esac
    fi
done
printf 'Indexed %s remote books; skipped %s root RAR/CBR archives pending extraction.\n' "$count" "$pending"
